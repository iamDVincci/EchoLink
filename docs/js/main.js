// 1. Tactical Toast Alerts
window.showTacticalToast = function(msg) {
  let toast = document.getElementById('tacticalToast');
  if (!toast) {
    toast = document.createElement('div');
    toast.id = 'tacticalToast';
    toast.className = 'toast-notice';
    document.body.appendChild(toast);
  }
  toast.innerHTML = `<span style="color:#00ff9d; font-weight:800;">[SYS]</span> <span>${msg}</span>`;
  toast.classList.add('show');
  clearTimeout(window._toastTimeout);
  window._toastTimeout = setTimeout(() => {
    toast.classList.remove('show');
  }, 3200);
};

document.addEventListener('DOMContentLoaded', () => {
  // 2. Navbar Scroll Dynamic Shadow
  const navbar = document.querySelector('.navbar');
  window.addEventListener('scroll', () => {
    if (window.scrollY > 40) {
      navbar.style.background = 'rgba(5, 8, 11, 0.92)';
      navbar.style.borderBottomColor = 'rgba(0, 255, 157, 0.22)';
    } else {
      navbar.style.background = 'rgba(5, 8, 11, 0.8)';
      navbar.style.borderBottomColor = 'rgba(0, 255, 157, 0.08)';
    }
  });

  // 3. Interactive Wire Protocol Byte Inspector
  const byteBlocks = document.querySelectorAll('.byte-block');
  const detailTitle = document.getElementById('packetDetailTitle');
  const detailBody = document.getElementById('packetDetailBody');

  const byteDetails = {
    'magic': {
      title: 'MAGIC BYTES // 0x41 0x47 ("AG")',
      body: '2-byte header identifier (0x4147). Validates that incoming UDP datagrams on port 51111 belong strictly to the EchoLink protocol, immediately discarding stray network packets without decrypting.'
    },
    'version': {
      title: 'PROTOCOL VERSION // 0x02',
      body: '1-byte wire-protocol version marker. Guarantees cross-platform protocol alignment between Android v2.4 (Kotlin) and iOS v2.4 (Swift) clients.'
    },
    'type': {
      title: 'PACKET TYPE // 0x01 (VOICE_PCM)',
      body: '1-byte payload discriminator. 0x01 designates 16 kHz 16-bit Mono PCM audio data; 0x02 designates PING/KEEPALIVE; 0x03 designates DTX silence heartbeat.'
    },
    'seq': {
      title: 'SEQUENCE NUMBER // 4-BYTE UINT32',
      body: 'Monotonically incremented sequence integer. Used by the jitter buffer on both platforms to detect dropped packets, compute packet loss statistics, and discard out-of-order UDP arrivals.'
    },
    'timestamp': {
      title: 'TRANSMIT TIMESTAMP // 8-BYTE UINT64',
      body: 'Nanosecond-precision host hardware timestamp. Allows the receiving device to measure one-way transit latency in real-time (displayed in the RF Stats HUD).'
    },
    'length': {
      title: 'PAYLOAD LENGTH // 2-BYTE UINT16 (640 B)',
      body: 'Specifies the exact byte size of the encrypted voice payload (standard 20 ms audio frame = 320 samples × 2 bytes = 640 bytes).'
    },
    'tag': {
      title: 'AEAD AUTHENTICATION TAG // 16-BYTE POLY1305',
      body: 'Cryptographic Poly1305 authentication tag generated by RFC 7539 ChaCha20-Poly1305. Verifies data integrity and authenticity, preventing tampering, spoofing, or replay attacks on local Wi-Fi.'
    },
    'payload': {
      title: 'ENCRYPTED AUDIO PAYLOAD // 640 BYTES PCM',
      body: '16 kHz 16-bit Mono raw PCM voice data encrypted with ChaCha20 symmetric stream cipher. When Discontinuous Transmission (DTX) silence suppression activates, payload transmission drops to zero.'
    }
  };

  byteBlocks.forEach((block) => {
    block.addEventListener('mouseenter', () => {
      byteBlocks.forEach((b) => b.classList.remove('active'));
      block.classList.add('active');
      const key = block.getAttribute('data-field');
      if (byteDetails[key] && detailTitle && detailBody) {
        detailTitle.textContent = byteDetails[key].title;
        detailBody.textContent = byteDetails[key].body;
      }
    });
  });

  // 4. Interactive Call Link & Tactical QR Code Generator
  const qrCanvas = document.getElementById('qrCodeCanvas');
  const roomInput = document.getElementById('roomNameInput');
  const genQrBtn = document.getElementById('generateQrBtn');
  const copyLinkBtn = document.getElementById('copyCallLinkBtn');

  function renderTacticalQr(text) {
    if (!qrCanvas) return;
    const ctx = qrCanvas.getContext('2d');
    const size = (qrCanvas.width = qrCanvas.height = 190);

    ctx.fillStyle = '#05080b';
    ctx.fillRect(0, 0, size, size);

    // Simple robust synthetic QR matrix pattern renderer
    const modules = 21;
    const modSize = Math.floor((size - 24) / modules);
    const offset = Math.floor((size - (modules * modSize)) / 2);

    // Seeded pseudo-random pattern based on text
    let hash = 0;
    for (let i = 0; i < text.length; i++) {
      hash = (hash << 5) - hash + text.charCodeAt(i);
      hash |= 0;
    }

    ctx.fillStyle = '#00ff9d';

    for (let r = 0; r < modules; r++) {
      for (let c = 0; c < modules; c++) {
        // Corner Position Finder Patterns
        const isTL = (r < 7 && c < 7);
        const isTR = (r < 7 && c >= modules - 7);
        const isBL = (r >= modules - 7 && c < 7);

        let fill = false;
        if (isTL || isTR || isBL) {
          let pr = r < 7 ? r : r - (modules - 7);
          let pc = c < 7 ? c : c - (modules - 7);
          fill = (pr === 0 || pr === 6 || pc === 0 || pc === 6 || (pr >= 2 && pr <= 4 && pc >= 2 && pc <= 4));
        } else {
          // Inner data matrix
          const pseudoVal = Math.sin(hash * 0.1 + r * 13 + c * 7);
          fill = pseudoVal > 0.15;
        }

        if (fill) {
          ctx.fillRect(offset + c * modSize, offset + r * modSize, modSize - 1, modSize - 1);
        }
      }
    }

    // High-tech Corner Targeting Brackets
    ctx.strokeStyle = '#00e5ff';
    ctx.lineWidth = 2;
    // Top Left
    ctx.strokeRect(4, 4, 12, 12);
    // Top Right
    ctx.strokeRect(size - 16, 4, 12, 12);
    // Bottom Left
    ctx.strokeRect(4, size - 16, 12, 12);
    // Bottom Right
    ctx.strokeRect(size - 16, size - 16, 12, 12);
  }

  if (genQrBtn && roomInput) {
    genQrBtn.addEventListener('click', () => {
      const room = roomInput.value.trim() || 'ALPHA-7';
      renderTacticalQr(`echolink://join?room=${encodeURIComponent(room)}`);
      window.showTacticalToast(`CALL LINK GENERATED FOR ROOM: ${room}`);
    });
    // Initial QR render
    renderTacticalQr('echolink://join?room=ALPHA-7');
  }

  if (copyLinkBtn && roomInput) {
    copyLinkBtn.addEventListener('click', () => {
      const room = roomInput.value.trim() || 'ALPHA-7';
      const link = `echolink://join?room=${encodeURIComponent(room)}&freq=51111`;
      navigator.clipboard.writeText(link).then(() => {
        window.showTacticalToast('UNIVERSAL CALL LINK COPIED TO CLIPBOARD');
      });
    });
  }

  // 5. Installation Platform Tabs (iOS vs Android)
  const installTabs = document.querySelectorAll('.install-tab-btn');
  const installPanels = document.querySelectorAll('.install-platform-content');

  installTabs.forEach((tab) => {
    tab.addEventListener('click', () => {
      installTabs.forEach((t) => t.classList.remove('active'));
      installPanels.forEach((p) => p.classList.remove('active'));
      tab.classList.add('active');
      const targetId = tab.getAttribute('data-platform');
      const targetPanel = document.getElementById(targetId);
      if (targetPanel) targetPanel.classList.add('active');
    });
  });

  // 6. Scroll-Triggered Fade-In & Telemetry Counter Animation
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.style.opacity = '1';
        entry.target.style.transform = 'translateY(0)';
      }
    });
  }, { threshold: 0.1 });

  document.querySelectorAll('.section-header, .tactical-frame, .step-card').forEach((el) => {
    el.style.opacity = '0';
    el.style.transform = 'translateY(24px)';
    el.style.transition = 'all 0.6s cubic-bezier(0.16, 1, 0.3, 1)';
    observer.observe(el);
  });
});
